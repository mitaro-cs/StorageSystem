/**
 * Русская типографика для коротких текстов: предлоги и союзы из одной-двух букв («в», «с», «на»)
 * не остаются в конце строки, а тире не начинает строку. Неразрывные пробелы — вместо обычных.
 */
export function typo(text: string): string {
	const short = /(^|[\s(«])([а-яёА-ЯЁ]{1,2}) +/g;
	let out = text;
	// Подряд идущие короткие слова («и на») — за несколько проходов: совпадения не пересекаются.
	for (let prev = ''; prev !== out;) {
		prev = out;
		out = out.replace(short, '$1$2 ');
	}
	return out.replace(/ +—/g, ' —');
}
